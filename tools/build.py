def search_index():
    idx = []
    for d in DOCS:
        if d["id"] == "welcome":
            continue
        idx.append({"id": d["id"], "file": d["file"], "path": d["path"],
                    "title": d["title"], "text": strip(d["html"])[:4000], "href": f'#{d["id"]}'})
    for p in POSTS:
        body = open(os.path.join(ROOT, "content", "blog", p["slug"] + ".html"),
                    encoding="utf-8").read()
        idx.append({"id": "blog/" + p["slug"], "file": p["slug"][:30] + ".md",
                    "path": f'blog/{p["slug"]}.md', "title": p["title"],
                    "text": strip(body)[:4000], "href": f'blog/{p["slug"]}.html'})
    return idx


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8") as f:
        f.write(text)
    return len(text.encode())


