# Art is emitted once per page as a <symbol> sprite and referenced with <use>,
# so a diagram shown in both a card and its project page costs one copy.
USED_ART = {}
SHARED_DEFS = ('<defs><marker id="a" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" '
               'markerHeight="6" orient="auto-start-reverse">'
               '<path d="M0 0 10 5 0 10z" fill="var(--fg-subtle)"/></marker></defs>')


def read_svg(kind, name):
    p = os.path.join(ROOT, "assets", "img", kind, name)
    if not os.path.exists(p):
        return ""
    return open(p, encoding="utf-8").read()


def art_use(kind, name, label=""):
    """Register the drawing in this page's sprite and return a <use> reference."""
    raw = read_svg(kind, name)
    if not raw:
        return ""
    key = f"{kind}-{name[:-4]}"
    if key not in USED_ART:
        vb = re.search(r'viewBox="([^"]+)"', raw)
        inner = re.sub(r"^<svg[^>]*>|</svg>$", "", raw)
        inner = re.sub(r"<defs>.*?</defs>", "", inner, flags=re.S)
        title = re.search(r"<title>(.*?)</title>", inner, re.S)
        inner = re.sub(r"<title>.*?</title>", "", inner, flags=re.S)
        USED_ART[key] = (vb.group(1) if vb else "0 0 640 200", inner,
                         title.group(1) if title else "")
    vb, _, title = USED_ART[key]
    alt = label or title
    return (f'<svg viewBox="{vb}" role="img" aria-label="{e(alt)}" preserveAspectRatio="xMidYMid meet">'
            f'<use href="#{key}"/></svg>')


def sprite():
    """Emit and clear this page's sprite sheet."""
    if not USED_ART:
        return ""
    syms = "".join(
        f'<symbol id="{k}" viewBox="{vb}"><title>{t}</title>{inner}</symbol>'
        for k, (vb, inner, t) in USED_ART.items()
    )
    USED_ART.clear()
    return ('<svg class="sprite" width="0" height="0" aria-hidden="true" focusable="false" '
            f'style="position:absolute;left:-9999px">{SHARED_DEFS}{syms}</svg>')


