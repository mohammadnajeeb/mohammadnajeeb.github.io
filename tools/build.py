# file-type colours, roughly Seti
EXT_STYLE = {
    "md": ("#519aba", "M"), "json": ("#cbcb41", "{}"), "py": ("#3572a5", "PY"),
    "tsx": ("#3178c6", "TS"), "ts": ("#3178c6", "TS"), "js": ("#f1e05a", "JS"),
    "ipynb": ("#f37726", "IPY"), "bib": ("#a074c4", "BIB"), "sh": ("#89e051", "$"),
    "ino": ("#00979d", "INO"), "fig": ("#f24e1e", "FIG"), "pdf": ("#e2574c", "PDF"),
    "html": ("#e34c26", "<>"),
}


def fico(fname):
    ext = fname.rsplit(".", 1)[-1].lower() if "." in fname else "md"
    color, letter = EXT_STYLE.get(ext, ("#8f8f8f", "•"))
    return f'<span class="tree__icon" style="color:{color}" aria-hidden="true">{letter}</span>'


def tabico(fname):
    ext = fname.rsplit(".", 1)[-1].lower() if "." in fname else "md"
    color, letter = EXT_STYLE.get(ext, ("#8f8f8f", "•"))
    return f'<span class="tab__icon" style="color:{color}" aria-hidden="true">{letter}</span>'


