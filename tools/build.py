# Each document is a dict: id, file, path, lang, title, crumb, html.
DOCS = []


def doc(did, file, path, lang, title, body, crumb=None, desc=""):
    DOCS.append({
        "id": did, "file": file, "path": path, "lang": lang, "title": title,
        "crumb": crumb or path, "html": body, "desc": desc,
    })


def dochead(kicker, title, sub, level=2):
    """level=1 on pages that hold a single document (blog posts, 404);
    level=2 on index.html, which carries one shell-level <h1> for all 27."""
    return (f'<div class="dochead"><div class="dochead__kicker">{kicker}</div>'
            f'<h{level} class="dochead__title">{e(title)}</h{level}>'
            f'<p class="dochead__sub">{sub}</p></div>')


def chips(items, on=()):
    return ('<div class="chips">' + "".join(
        f'<span class="chip{" is-on" if x in on else ""}">{e(x)}</span>' for x in items
    ) + "</div>") if items else ""


def linkbtn(label, url, ic, primary=False):
    ext = ' target="_blank" rel="noopener"' if url.startswith("http") else ""
    cls = "btn" if primary else "btn btn--ghost"
    return f'<a class="{cls}" href="{e(url)}"{ext}>{icon(ic)}{e(label)}</a>'


