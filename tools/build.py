def wrap(d, active):
    return (f'<article class="doc{" is-active" if d["id"] == active else ""}" '
            f'id="doc-{e(d["id"])}" data-doc="{e(d["id"])}" data-file="{e(d["file"])}" '
            f'data-path="{e(d["path"])}" data-lang="{e(d["lang"])}" '
            f'data-title="{e(d["title"])}">{d["html"]}</article>')


def tabs_for(ids, active):
    by_id = {d["id"]: d for d in DOCS}
    out = ""
    for i in ids:
        d = by_id.get(i)
        if not d:
            continue
        sel = "true" if i == active else "false"
        out += (f'<button class="tab" role="tab" data-tab="{e(i)}" aria-selected="{sel}">'
                f'{tabico(d["file"])}<span class="tab__name">{e(d["file"])}</span>'
                f'<span class="tab__close" data-close="{e(i)}" role="presentation">✕</span></button>')
    return out


def crumb_for(path):
    parts = [p for p in path.split("/") if p]
    out = '<span>portfolio</span>'
    for p in parts:
        out += f'<span class="breadcrumb__sep">›</span><span>{e(p)}</span>'
    return out


def strip(s):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", s)).strip()


