# ================================================================ sidebar
def up_of(depth):
    """Prefix for assets. depth="abs" means site-absolute (used by 404.html,
    which GitHub Pages serves from whatever URL the visitor typed)."""
    return "/" if depth == "abs" else "../" * depth


def href_doc(depth, doc_id):
    """Link to a document. Off the root it has to walk back to index.html."""
    if depth == "abs":
        return "/index.html#" + doc_id
    return ("../" * depth + "index.html" if depth else "") + "#" + doc_id


def tree(depth=0):
    up = up_of(depth)

    def leaf(fname, href, pad=36, meta=""):
        return (f'<a class="tree__row" style="padding-left:{pad}px" href="{e(href)}" '
                f'role="treeitem" data-file="{e(fname)}">{fico(fname)}'
                f'<span class="tree__label">{e(fname)}</span>'
                + (f'<span class="tree__meta">{e(meta)}</span>' if meta else "") + "</a>")

    def folder(name, children, open_=True, pad=18):
        return (
            f'<div class="tree__group" data-collapsed="{str(not open_).lower()}">'
            f'<button class="tree__row" style="padding-left:{pad}px" aria-expanded="{str(open_).lower()}" '
            f'role="treeitem" data-folder="{e(name)}">'
            f'<span class="tree__chevron">{icon("chevron")}</span>'
            f'<span class="tree__label">{e(name)}</span></button>'
            f'<div class="tree__children">{children}</div></div>'
        )

    exp = "".join(leaf(r["file"], href_doc(depth, f'experience/{r["id"]}')) for r in EXPERIENCE)
    prj = "".join(leaf(p["file"], href_doc(depth, f'projects/{p["id"]}')) for p in PROJECTS)
    blg = "".join(
        leaf(post["slug"][:30] + ".md", f'{up}blog/{post["slug"]}.html')
        for post in POSTS
    )
    return (
        '<div class="tree" role="tree" aria-label="Explorer">'
        + folder("NAJEEB-PORTFOLIO", (
            leaf("README.md", href_doc(depth, "readme"))
            + folder("about", leaf("about.md", href_doc(depth, "about"), 54)
                     + leaf("education.json", href_doc(depth, "education"), 54), True, 36)
            + folder("experience", exp.replace('padding-left:36px', 'padding-left:54px'), True, 36)
            + folder("projects", prj.replace('padding-left:36px', 'padding-left:54px'), True, 36)
            + folder("blog", blg.replace('padding-left:36px', 'padding-left:54px'), False, 36)
            + leaf("publications.bib", href_doc(depth, "publications"))
            + leaf("skills.json", href_doc(depth, "skills"))
            + leaf("contact.sh", href_doc(depth, "contact"))
            + leaf("resume.pdf", f'{up}{PROFILE["resume"]}')
        ), True, 8)
        + "</div>"
    )


def scm_view(depth=0):
    """Career as a git log. Newest first; HEAD is the current role."""
    items = []
    for r in EXPERIENCE:
        items.append((r["start"], f"feat({r['id']}): {r['role'].lower()}",
                      r["org"].split(",")[0], r["period"],
                      href_doc(depth, f'experience/{r["id"]}'),
                      len(r["highlights"]) * 37 + 12, r["current"]))
    for ed in EDUCATION[:3]:
        yr = ed["period"].split("—")[0].strip().split()[-1]
        items.append((f"{yr}-01", f"chore(edu): {ed['degree'].split(',')[0].lower()}",
                      ed["org_short"], ed["period"], href_doc(depth, "education"), 84, False))
    for p in PUBS:
        short = p["title"].lower()
        if len(short) > 46:
            short = short[:46].rsplit(" ", 1)[0] + "…"
        items.append((f'{p["year"]}-06', f'docs(paper): {short}',
                      p["publisher"], p["year"], href_doc(depth, "publications"), 827, False))
    items.sort(key=lambda x: x[0], reverse=True)

    rows = ""
    for i, (_, msg, org, period, href, adds, cur) in enumerate(items):
        h = format(abs(hash(msg)) % 0xfffffff, "07x")
        rows += (
            f'<div class="scm__commit{" is-head" if i == 0 else ""}">'
            f'<div class="scm__graph"><span class="scm__dot"></span></div>'
            f'<div class="scm__body">'
            f'<a class="scm__msg" href="{e(href)}">{e(msg)}</a>'
            f'<div class="scm__meta"><span class="scm__hash">{h}</span> · {e(org)} · {e(period)} '
            f'<span class="scm__stat">+{adds}</span>'
            + ('<span class="scm__tag">HEAD → main</span>' if i == 0 else "")
            + "</div></div></div>"
        )
    return f'<div class="scm">{rows}</div>'


